function detectExperience(
  message = ""
) {
  const text = String(message)
    .toLowerCase()
    .trim();

  /*
   * מתחיל / ללא ניסיון.
   * נבדק ראשון כדי ש-"אף פעם לא שיחקתי"
   * לא יזוהה בטעות כבעל ניסיון.
   */
  if (
    /מתחיל|מתחילה|מתחיל מאפס|מתחילה מאפס|חדש|חדשה|פעם ראשונה|לא שיחק|לא שיחקה|לא שיחקתי|אף פעם לא שיחקתי|מעולם לא שיחקתי|אין לי ניסיון|בלי ניסיון/.test(
      text
    )
  ) {
    return "beginner";
  }

  /*
   * ניסיון קודם.
   */
  if (
    /שיחק בעבר|שיחקה בעבר|שיחקתי בעבר|שיחקתי פעם|כבר שיחקתי|כבר שיחק|כבר שיחקה|כבר משחק|כבר משחקת|אני משחק|אני משחקת|משחק טניס|משחקת טניס|משחק כבר|משחקת כבר|משחק כמה שנים|משחקת כמה שנים|משחק מספר שנים|משחקת מספר שנים|יש לי ניסיון|יש לו ניסיון|יש לה ניסיון|יש לי קצת ניסיון|יש לו קצת ניסיון|יש לה קצת ניסיון|יש לי ניסיון קודם|שיחקתי כמה שנים|שיחק כמה שנים|שיחקה כמה שנים|שיחקתי כמה חודשים|שיחק כמה חודשים|שיחקה כמה חודשים|מתקדם|מתקדמת|מנוסה/.test(
      text
    )
  ) {
    return "experienced";
  }

  return null;
}

function detectAdultFormat(
  message = ""
) {
  const text = String(message)
    .toLowerCase()
    .trim();

  if (
    /קבוצה|קבוצתי|קבוצתית|חוג/.test(
      text
    )
  ) {
    return "group";
  }

  if (
    /אישי|אישית|פרטי|פרטית|מאמן אישי/.test(
      text
    )
  ) {
    return "personal";
  }

  return null;
}

/*
 * מאפשר לזהות בקשת המלצה גם בניסוחים
 * שלא נתפסו עדיין ב-conversationIntentService.
 */
function isRecommendationRequest(
  message = "",
  conversationIntent = {}
) {
  if (
    conversationIntent.stage ===
    "recommendation"
  ) {
    return true;
  }

  const text = String(message)
    .toLowerCase()
    .trim();

  return (
    /מה מתאים|מה יתאים|מה מומלץ|תמליץ|ממליץ|מסגרת מתאימה|מסגרת שמתאימה|מחפש לו מסגרת|מחפשת לו מסגרת|מחפש לה מסגרת|מחפשת לה מסגרת|איזה חוג|איזו קבוצה|איזה מסלול/.test(
      text
    )
  );
}

function getRecommendationResponse({
  userMessage = "",
  userProfile = {},
  conversationIntent = {},
}) {
  if (
    !isRecommendationRequest(
      userMessage,
      conversationIntent
    )
  ) {
    return null;
  }

  const age =
    Number(userProfile.age);

  const experience =
    detectExperience(
      userMessage
    ) ||
    userProfile.experience ||
    null;

  const adultFormat =
    detectAdultFormat(
      userMessage
    );

  /*
   * ילד עם גיל ידוע.
   */
  if (
    Number.isFinite(age) &&
    age > 0 &&
    age < 18
  ) {
    /*
     * ילד מתחיל.
     */
    if (
      experience === "beginner"
    ) {
      return [
        "מצוין 😊",
        "",
        `לילד בן ${age} שמתחיל מאפס, חוג קבוצתי למתחילים הוא בדרך כלל נקודת פתיחה מצוינת.`,
        "באימונים עובדים בהדרגה על היכרות עם המחבט והכדור, קואורדינציה, תנועה במגרש, חבטות בסיסיות והבנת המשחק.",
        "",
        "המטרה היא קודם כול לבנות ביטחון והנאה מהמשחק, ורק אחר כך להתקדם לטכניקה מורכבת יותר.",
        "",
        "באיזה סניף יהיה לכם הכי נוח — גלי הדר בראשון לציון או בית חשמונאי?"
      ].join("\n");
    }

    /*
     * ילד עם ניסיון קודם.
     */
    if (
      experience === "experienced"
    ) {
      return [
        "יופי 😊",
        "",
        `בגיל ${age} ועם ניסיון קודם בטניס, כדאי להתאים לו קבוצה לפי הרמה בפועל ולא רק לפי הגיל.`,
        "",
        "כדי שאכוון נכון — כמה זמן הוא שיחק בעבר ובאיזו רמה בערך?"
      ].join("\n");
    }

    /*
     * הגיל ידוע, רמת הניסיון עדיין לא.
     */
    return [
      "בשמחה 😊",
      "",
      `לפי גיל ${age}, אפשר להתאים קבוצה שמתאימה לגיל ולרמת המשחק.`,
      "",
      "הוא מתחיל לגמרי או שכבר שיחק בעבר?"
    ].join("\n");
  }

  /*
   * מבוגר עם גיל ידוע.
   */
  if (
    Number.isFinite(age) &&
    age >= 18
  ) {
    /*
     * המשתמש בחר קבוצה.
     */
    if (
      adultFormat === "group"
    ) {
      return [
        "מעולה 😊",
        "",
        experience === "experienced"
          ? "למי שכבר יש ניסיון ומעדיף קבוצה, כדאי להתאים קבוצה לפי הרמה בפועל כדי שהאימון יהיה מאתגר ומתאים."
          : "למתחיל שמעדיף קבוצה, אימון קבוצתי הוא בדרך כלל בחירה מצוינת — לומדים את הבסיס בהדרגה וגם נהנים מהאווירה והמשחק עם אחרים.",
        "",
        "באיזה סניף יהיה לך הכי נוח להתאמן?",
        "• גלי הדר – ראשון לציון",
        "• בית חשמונאי"
      ].join("\n");
    }

    /*
     * המשתמש בחר אימון אישי.
     */
    if (
      adultFormat === "personal"
    ) {
      return [
        "מעולה 😊",
        "",
        experience === "experienced"
          ? "אם כבר יש לך ניסיון, אימון אישי יכול להיות מצוין לעבודה ממוקדת על נקודות ספציפיות בטכניקה וברמת המשחק."
          : "אימון אישי מתאים במיוחד למי שרוצה קצב אישי, עבודה ממוקדת על טכניקה והרבה תשומת לב מהמאמן.",
        "",
        "באיזה סניף יהיה לך הכי נוח להתאמן?",
        "• גלי הדר – ראשון לציון",
        "• בית חשמונאי"
      ].join("\n");
    }

    /*
     * מבוגר מתחיל.
     */
    if (
      experience === "beginner"
    ) {
      return [
        "בשמחה 😊",
        "",
        "למבוגר שמתחיל מאפס, בדרך כלל הכי נכון להתחיל בקבוצת מתחילים או באימון אישי, לפי ההעדפה.",
        "",
        "אתה מעדיף קבוצה או מסגרת אישית יותר?"
      ].join("\n");
    }

    /*
     * מבוגר עם ניסיון.
     */
    if (
      experience === "experienced"
    ) {
      return [
        "בשמחה 😊",
        "",
        "מאחר שכבר יש לך ניסיון בטניס, כדאי להתאים את המסגרת לפי הרמה הנוכחית והמטרה שלך.",
        "",
        "מה חשוב לך יותר כרגע — שיפור טכניקה, כושר או יותר משחקים?"
      ].join("\n");
    }

    return [
      "בשמחה 😊",
      "",
      "יש מסגרות למבוגרים ברמות שונות.",
      "",
      "אתה מתחיל לגמרי או שכבר שיחקת בעבר?"
    ].join("\n");
  }

  /*
   * אין עדיין גיל.
   */
  return [
    "בשמחה 😊",
    "",
    "כדי להמליץ על מסגרת שמתאימה באמת, חשוב לדעת גיל ורמת ניסיון.",
    "",
    "בן או בת כמה המתאמן או המתאמנת?"
  ].join("\n");
}

module.exports = {
  getRecommendationResponse,
  detectExperience,
  detectAdultFormat,
  isRecommendationRequest,
};